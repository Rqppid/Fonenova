#!/usr/bin/env python3
"""
Rebuild the social banners and the link-preview card from the site's own brand assets.

    python3 brand/social/build/build.py              # five banners into brand/social/
    python3 brand/social/build/build.py --og         # also public/images/og-cover.jpg

Nothing here is drawn by eye or traced. The inputs are the repo's own files, so the images
cannot drift from the site:

  - the tile                public/icon.svg, verbatim
  - the wordmark outlines   components/logo-paths.ts (itself generated by
                            brand/build-logo-paths.py), so a change to the logo font flows
                            through to every banner on the next run
  - the type                Inter and Space Grotesk, the two faces app/layout.tsx loads,
                            taken from .next/static/media after a `pnpm build`

Needs: fonttools and brotli (to identify the font files), Node with Playwright, and a
Chromium. Set PLAYWRIGHT_MODULE and CHROME_PATH if they are not where render.mjs expects.

Design notes, so the next person does not have to rediscover them:

  - Every platform draws an avatar over the banner's bottom-left, and LinkedIn also draws
    the company logo there. Content is kept clear of that corner, and the Facebook cover
    stays inside the narrower band that mobile crops to. render.mjs fails the run if any
    content box leaves the frame.
  - The field is dark rather than solid brand blue: a blue field forces a blue tile on blue.
  - Banners render at 2x so they stay sharp on retina. Aspect ratios are exact.
"""

import argparse
