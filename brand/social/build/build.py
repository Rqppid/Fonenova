META = {
    "stack": '<span><b>Trade only</b></span><i></i><span>Belfast, Northern Ireland</span><i></i>'
             '<span>UK, Ireland &amp; Europe</span><i></i><span>fonenova.com</span>',
    "row": '<span><b>Trade only</b></span><i></i><span>Belfast, Northern Ireland</span><i></i>'
           '<span>fonenova.com</span>',
}

SPARK = "M50 28 Q54.8 45.6 74 50 Q54.8 54.4 50 72 Q45.2 54.4 26 50 Q45.2 45.6 50 28 Z"

# The lockup used to be sized by the height of its whole box (1084 units, caps 686). The
# wordmark's box is different now, so convert: keep the CAP height in pixels identical to
# what each preset was tuned with, whatever the new box is.
OLD_BOX_H, OLD_CAP = 1084, 686


def load_logo():
    src = (ROOT / "components" / "logo-paths.ts").read_text(encoding="utf-8")
    s = lambda k: re.search(rf'export const {k} = "([^"]+)"', src).group(1)
    full = re.search(
        r"export const FULL = \{ x: 0, y: (-?\d+), w: (\d+), h: (\d+), wordDx: ([\d.]+), subDx: ([\d.]+) \}", src)
    return dict(
        fone=s("FONE_PATH"), nova=s("NOVA_PATH"), sub=s("SUBLINE_PATH"),
        cap=int(re.search(r"export const CAP_HEIGHT = (\d+)", src).group(1)),
        y=int(full.group(1)), w=int(full.group(2)), h=int(full.group(3)),
        word_dx=float(full.group(4)), sub_dx=float(full.group(5)),
    )


def lockup_svg(lp, lock_px):
    cap_px = lock_px * OLD_CAP / OLD_BOX_H
    height = cap_px * lp["h"] / lp["cap"]
    return (
        f'<svg class="lockup" style="height:{height:.2f}px" viewBox="0 {lp["y"]} {lp["w"]} {lp["h"]}" '
        f'xmlns="http://www.w3.org/2000/svg"><g transform="translate({lp["word_dx"]} 0)">'
        f'<path fill="#ffffff" d="{lp["fone"]}"/><path fill="#0099f2" d="{lp["nova"]}"/></g>'
        f'<path transform="translate({lp["sub_dx"]} 0)" fill="#ffffff" fill-opacity="0.5" d="{lp["sub"]}"/></svg>'
    )


def find_fonts():
    """Inter and Space Grotesk, Latin subsets, from the Next build (run `pnpm build` first)."""
    found = {}
    for f in glob.glob(str(ROOT / ".next" / "static" / "media" / "*.woff2")):
        tt = TTFont(f, lazy=True)
        fam = (tt["name"].getDebugName(16) or tt["name"].getDebugName(1) or "")
        cmap = tt.getBestCmap()
        if not all(c in cmap for c in (0x41, 0x57, 0x26, 0x61, 0x2E)):
            continue  # not the Latin subset
        key = "inter" if fam.startswith("Inter") else "grotesk" if fam.startswith("Space Grotesk") else None
        if key and "fvar" in tt:
            found[key] = pathlib.Path(f)
    missing = {"inter", "grotesk"} - set(found)
    if missing:
        sys.exit(f"Missing {sorted(missing)} under .next/static/media. Run `pnpm build` first.")
    return found


