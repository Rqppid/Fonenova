def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--og", action="store_true", help="also write public/images/og-cover.jpg (1200x630, 1x, JPEG)")
    ap.add_argument("--out", default=str(ROOT / "brand" / "social"), help="where the 2x PNG banners go")
    args = ap.parse_args()

    lp = load_logo()
    fonts = find_fonts()
    tile = (ROOT / "public" / "icon.svg").read_text(encoding="utf-8").strip()

    work = pathlib.Path(tempfile.mkdtemp(prefix="fn-banners-"))
    try:
        jobs = []
        for name, p in PRESETS.items():
            m = re.search(r"--lock:(\d+)px", p["vars"])
            html = PAGE.substitute(
                inter=fonts["inter"], grotesk=fonts["grotesk"], vars=p["vars"], cls="row" if p["row"] else "stack",
                spark=SPARK, tile=tile, lockup=lockup_svg(lp, int(m.group(1))),
                meta=META["row" if p["row"] else "stack"],
            )
            (work / f"{name}.html").write_text(html, encoding="utf-8")
            jobs.append(dict(name=name, w=p["w"], h=p["h"], scale=2, out=str(pathlib.Path(args.out) / f"{name}@2x.png")))
            if args.og and name == "fonenova-share-card-1200x630":
                jobs.append(dict(name=name, w=p["w"], h=p["h"], scale=1,
                                 out=str(ROOT / "public" / "images" / "og-cover.jpg"), jpeg=True))
        (work / "jobs.json").write_text(json.dumps(jobs), encoding="utf-8")
        subprocess.run(["node", str(HERE / "render.mjs"), str(work)], check=True)
    finally:
        shutil.rmtree(work, ignore_errors=True)


if __name__ == "__main__":
    main()
